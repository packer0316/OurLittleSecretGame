/** Records appear only after the corresponding interaction. */
export function preludeRecords(s){
  const out=[],h=s.home||{step:0,notes:[]},r=s.road||{step:0,notes:[]};
  if(h.step>=1)out.push(['阿哲寄回的照片','阿哲在整理慈雲寺的舊錄音，寄回一張六人合照，是我自己的那一張。字條寫著「02:47，聽到這裡再停」。']);
  if(h.step>=3)out.push(['23:47 的來電','阿哲說後面的門打不開，接著把第一句原樣重複了一次。門外有人敲三下，自稱管理員，對講機卻沒有亮。'+(h.answered?'我隔著門問了一句，它用我的聲音原樣還給我。':'我沒有出聲。')]);
  if(h.step>=4)out.push(['門下的封口','撕下的信封封口從門外滑回來，多了一行「照片收到，請回答」。管理室的話筒垂著，沒有人說話。先拿玄關矮櫃的鑰匙與手電筒。']);
  const optional={calendar:['月曆','回阿哲的電話，我拖了兩個禮拜。十二日到十三日之間多了一道不是我劃的筆痕。'],window:['窗外雨聲','七樓窗外有人拖椅子。我停，它也停。'],message:['沒送出的語音','十月三十日我錄過一句「廟裡的事我不想再談」，沒有送出。今天下午那段的結尾，多了一聲拖椅子的聲音。']};
  for(const id of h.notes)if(optional[id])out.push(optional[id]);
  if(r.step>=1)out.push(['候車亭','濕透的長椅中央留著一塊乾的，底下是阿哲的電池盒。去石橋對面的公告找管理單位。']);
  if(r.step>=2)out.push(['住戶公告','全里 2024 年撤離，廟內清點由榮昌紙紮行代管。底下的舊告示寫著：七月初一借聲，一聲一尊；門外有人喊名，勿應。']);
  if(r.step>=3)out.push(['工作桌上的手','工牌屬於郭建成，46 歲，代管廟務的人。送貨簿最後一頁寫著「借一聲，還一尊。欠到今年，二十八尊」。光一移開，那隻手就換了位置。']);
  if(r.step>=4)out.push(['攝影機裡的十三秒','十月二十七日，阿哲說三天弄完，要把設備搬進廟裡。鏡頭錄到桌下伸出一隻手，他沒有看見。設備箱標籤寫著正殿西桌。']);
  if(r.notes.includes('car'))out.push(['車內','車上的時鐘停在我接電話的 23:47。空的副駕駛座，安全帶是扣著的。']);
  if(r.notes.includes('kiln'))out.push(['焚化爐','溫的爐灰裡有瓷牙和熔掉的鈕扣。紙人不會有牙。']);
  if(r.peishan)out.push(['佩珊的回電','佩珊已經報警。阿哲的號碼連續三晚 23:47 打給她，她沒接。志豪二號接了，柏翰七號接了，兩個人都出了門沒回來。她要我找阿哲的手機，看最後一段錄音是哪一天的。不管誰叫，都不要應。']);
  return out;
}
